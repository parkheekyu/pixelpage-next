export interface RunResult { text: string; model: string; usage: { input: number; output: number }; stop_reason: string | null; refusal?: string }

/** 분석 실행. 긴 출력이므로 스트리밍으로 받고 최종 메시지만 반환. */
export async function runAnalysis(kind: AnalysisKind, userContent: string, opts?: { effort?: "low" | "medium" | "high" | "xhigh" }): Promise<RunResult> {
  const stream = client().messages.stream({
    model: MODEL,
    max_tokens: 24000,
    // 시장 리서치는 서버 웹 검색 도구로 실제 조사
    ...(kind === "market" || kind === "research" ? { tools: [{ type: "web_search_20260209" as const, name: "web_search" as const, max_uses: 25 }] } : {}),
    system: [{ type: "text", text: SYSTEM[kind], cache_control: { type: "ephemeral" } }],
    thinking: { type: "adaptive" },
    output_config: { effort: opts?.effort ?? "high" },
    messages: [{ role: "user", content: userContent }],
  });
  const msg = await stream.finalMessage();
  const text = msg.content.filter((b): b is Anthropic.TextBlock => b.type === "text").map((b) => b.text).join("\n");
  return {
    text, model: msg.model, stop_reason: msg.stop_reason,
    usage: { input: msg.usage.input_tokens + (msg.usage.cache_read_input_tokens ?? 0) + (msg.usage.cache_creation_input_tokens ?? 0), output: msg.usage.output_tokens },
    refusal: msg.stop_reason === "refusal" ? (msg.stop_details?.explanation ?? "안전 정책으로 거부됨") : undefined,
  };
}
