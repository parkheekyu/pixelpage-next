import type { ResearchInput } from "./types";

/** 퍼플렉시티(Research 모드)에 붙여 넣을 조사 프롬프트 3개. API 없이 구독으로 조사할 때 사용. */
export function perplexityPrompts(name: string, r: ResearchInput): { title: string; prompt: string }[] {
  const base = `고객사: ${name}\n상품/서비스: ${r.product ?? ""}\n타깃 고객: ${r.target ?? ""}${r.competitors ? `\n알려진 경쟁사/대안: ${r.competitors}` : ""}\n\n한국 시장 기준으로 조사하고, 모든 항목에 출처 링크를 붙여 주세요. 커뮤니티·후기 표현은 원문 그대로 인용해 주세요.`;
  return [
    { title: "1. 타깃 목소리 (커뮤니티·후기)", prompt: `${base}\n\n이 타깃이 실제로 모이는 한국 커뮤니티(네이버 카페·지식iN·블로그, 유튜브 댓글, 인스타·스레드, 디시·클리앙·블라인드 등)와 후기·Q&A를 최대한 찾아서 정리해 주세요.\n1) 이들이 겪는 페인포인트와 원하는 결과(니즈)를 빈도 순으로\n2) 이들이 실제로 쓰는 표현·단어·검색어를 원문 그대로 최소 15개 (출처 포함)\n3) 이 상품군을 살 때 나오는 걱정·의심·거절 이유 (원문 인용)\n4) 이미 시도해 본 대안과 그에 대한 불만` },
    { title: "2. 경쟁사·시장 변화", prompt: `${base}\n\n같은 문제를 푸는 경쟁사·대안 상위 5~8곳(알려진 곳 포함)을 찾아 각각 정리해 주세요: 가격/오퍼(무료·보장·체험), 메인 헤드라인과 CTA 카피(원문), 내세우는 증거(후기·수치·자격·미디어), 광고 포맷과 채널, 최근 6개월 변화(신규 진입·가격·메시지 변경·이슈). 그리고 시장 전체의 최근 변화(규제, 트렌드, 뉴스)도 정리해 주세요.` },
    { title: "3. 키워드·광고 레퍼런스", prompt: `${base}\n\n1) 이 타깃이 정보 탐색 → 비교 → 구매 단계에서 쓰는 검색 키워드를 단계별로 20개 이상 (네이버·유튜브·구글 기준, 가능하면 검색량·경쟁 정도)\n2) 지금 이 시장에서 돌고 있는 광고·콘텐츠의 메시지 패턴(문제제기형/비교형/후기형/권위형 등)과 실제 카피 예시(원문 인용)\n3) 잘 되는 것으로 보이는 콘텐츠(조회수·댓글 반응 근거)와 그 이유` },
  ];
}

/** 특정 주제 하나를 퍼플렉시티에 물을 때 */
export function perplexityTopicPrompt(name: string, r: ResearchInput, topic: string): string {
  return `고객사: ${name}\n상품/서비스: ${r.product ?? ""}\n타깃 고객: ${r.target ?? ""}${r.competitors ? `\n알려진 경쟁사/대안: ${r.competitors}` : ""}\n\n조사 주제: ${topic}\n\n한국 시장 기준으로 조사해 주세요. 항목마다 출처 URL 을 붙이고, 같은 말을 반복하지 말고 번호 목록이나 표로 정리해 주세요. 커뮤니티·후기의 실제 표현은 원문 그대로 인용해 주세요. 마지막에 '광고·랜딩페이지에 바로 쓸 시사점 5개' 를 붙여 주세요.`;
}
